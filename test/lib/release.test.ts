import { describe, expect, it } from "vitest";

import { ENDING_SOON_DAYS, releaseStatus } from "~/lib/release";

// 仕様書 010（公開終了・見逃し）と 011（近日公開）の表示の規則。
describe("公開日についての表示", () => {
  describe("公開後：公開◯週目（仕様書 010）", () => {
    const today = "2026-11-10";
    it.each([
      ["2026-11-09", "公開1週目", false], // 1日後
      ["2026-11-04", "公開1週目", false], // 6日後
      ["2026-11-03", "公開2週目", false], // 7日後
      ["2026-10-28", "公開2週目", false], // 13日後
      ["2026-10-27", "公開3週目", false], // 14日後
      ["2026-10-14", "公開4週目", false], // 27日後
      ["2026-10-13", "公開5週目・そろそろ上映終了かも", true], // 28日後
      ["2026-10-01", "公開6週目・そろそろ上映終了かも", true], // 40日後
    ])("公開日 %s → %s（AC1・AC2）", (release, label, warning) => {
      expect(releaseStatus(release, today)).toEqual({ kind: "showing", label, warning });
    });

    it("「そろそろ上映終了かも」は、公開から28日（4週間）で出る", () => {
      expect(ENDING_SOON_DAYS).toBe(28);
    });

    it("公開日の当日は「今日公開」（仕様書 011 の規則を優先）", () => {
      expect(releaseStatus("2026-11-10", today)).toEqual({ kind: "showing", label: "今日公開", warning: false });
    });
  });

  describe("公開前（仕様書 011）", () => {
    // 2026-10-25 は日曜日。
    it.each([
      ["2026-10-25", "2026-10-26", "明日公開"], // 翌日が来週の月曜でも「明日」を優先（AC2）
      ["2026-10-25", "2026-10-27", "来週公開（10/27）"],
      ["2026-10-25", "2026-11-01", "来週公開（11/1）"], // 来週の日曜（月をまたいでも「来週」を優先）
      ["2026-10-25", "2026-11-02", "来月公開（11/2）"],
      ["2026-10-25", "2026-11-30", "来月公開（11/30）"],
      ["2026-10-25", "2026-12-25", "12月25日公開"],
      ["2026-10-25", "2027-01-08", "2027年1月8日公開"],
      // 2026-10-05 は月曜日。
      ["2026-10-05", "2026-10-07", "今週公開（10/7）"],
      ["2026-10-05", "2026-10-11", "今週公開（10/11）"], // 同じ週の日曜
      ["2026-10-05", "2026-10-12", "来週公開（10/12）"],
      ["2026-10-05", "2026-10-20", "今月公開（10/20）"],
      ["2026-10-05", "2026-10-31", "今月公開（10/31）"],
      // 年末：2026-12-28 は月曜日。
      ["2026-12-28", "2027-01-02", "今週公開（1/2）"],
      ["2026-12-28", "2027-01-05", "来週公開（1/5）"],
      ["2026-12-28", "2027-01-20", "来月公開（1/20）"],
      ["2026-12-01", "2027-02-01", "2027年2月1日公開"],
    ])("今日 %s・公開日 %s → %s（AC1）", (today, release, label) => {
      expect(releaseStatus(release, today)).toEqual({ kind: "upcoming", label, warning: false });
    });
  });

  it("公開日がない・不正なときは「公開日未定」", () => {
    for (const value of [null, undefined, "", "2026/10/01", "2026-02-30"]) {
      expect(releaseStatus(value, "2026-10-25")).toEqual({ kind: "unknown", label: "公開日未定", warning: false });
    }
  });
});
